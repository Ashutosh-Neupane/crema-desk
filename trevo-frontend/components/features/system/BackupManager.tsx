"use client";

import { useQuery } from "@tanstack/react-query";
import { frappeMethod } from "@/lib/frappe/client";
import { PageHeader } from "@/components/PageHeader";
import { Card } from "@/components/shadcn/card";
import { Button } from "@/components/shadcn/button";
import { Skeleton } from "@/components/Skeleton";
import { Download, Database, RefreshCw, HardDrive } from "lucide-react";
import { formatDateTime } from "@/lib/utils/formatNumber";

interface Backup {
  name: string;
  size?: number;
  creation?: string;
  file_url?: string;
}

/**
 * Backups page — lists available backups created via Frappe's
 * frappe.utils.backups.get_backups and lets the user fetch fresh backups.
 */
export function BackupManager() {
  const { data, isLoading, refetch, isFetching } = useQuery({
    queryKey: ["backups"],
    queryFn: async () => {
      const backups = await frappeMethod<{ data?: Backup[] }>(
        "frappe.utils.backups.get_backups",
      ).catch(() => null);
      return backups?.data ?? [];
    },
    staleTime: 60_000,
  });

  const list = data ?? [];

  return (
    <div className="space-y-4">
      <PageHeader
        title="Backups"
        description="View and download database and file backups generated by Frappe."
        actions={
          <Button
            size="sm"
            onClick={() => refetch()}
            disabled={isFetching}
            className="gap-1.5"
          >
            <RefreshCw className={(isFetching ? "animate-spin " : "") + "h-4 w-4"} />
            Refresh
          </Button>
        }
      />

      <Card className="p-6">
        <div className="mb-4 flex items-center gap-2">
          <Database className="h-5 w-5 text-zinc-400" />
          <h2 className="text-sm font-medium text-zinc-900 dark:text-zinc-100">
            Available Backups
          </h2>
        </div>

        {isLoading ? (
          <div className="space-y-3">
            {Array.from({ length: 4 }).map((_, i) => (
              <Skeleton key={i} className="h-12 w-full" />
            ))}
          </div>
        ) : list.length === 0 ? (
          <div className="flex flex-col items-center justify-center rounded-lg border border-dashed border-zinc-300 py-12 text-center dark:border-zinc-700">
            <HardDrive className="h-8 w-8 text-zinc-300 dark:text-zinc-600" />
            <p className="mt-2 text-sm text-zinc-500">No backups found.</p>
            <p className="mt-1 text-xs text-zinc-400">
              Backups are generated by the Frappe scheduler. Refresh to see new backups.
            </p>
          </div>
        ) : (
          <ul className="divide-y divide-zinc-100 dark:divide-zinc-800">
            {list.map((backup) => (
              <li
                key={backup.name ?? String(backup)}
                className="flex items-center justify-between py-3"
              >
                <div className="min-w-0">
                  <p className="truncate text-sm font-medium text-zinc-900 dark:text-zinc-100">
                    {String(backup.name ?? backup.file_url ?? "Backup")}
                  </p>
                  <p className="text-xs text-zinc-500">
                    {formatDate(backup.creation)}
                    {typeof backup.size === "number" ? ` · ${formatBytes(backup.size)}` : ""}
                  </p>
                </div>
                {backup.file_url ? (
                  <a
                    href={backup.file_url}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="inline-flex h-8 items-center gap-1.5 rounded-lg border border-zinc-300 px-3 text-xs font-medium hover:bg-zinc-50 dark:border-zinc-700 dark:hover:bg-zinc-800"
                  >
                    <Download className="h-3.5 w-3.5" />
                    Download
                  </a>
                ) : (
                  <span className="text-xs text-zinc-400">—</span>
                )}
              </li>
            ))}
          </ul>
        )}
      </Card>
    </div>
  );
}

function formatDate(v: unknown): string {
  if (!v) return "-";
  const d = new Date(String(v));
  if (Number.isNaN(d.getTime())) return "-";
  return formatDateTime(d.toISOString(), false);
}

function formatBytes(bytes: number): string {
  if (bytes <= 0) return "0 B";
  const units = ["B", "KB", "MB", "GB"];
  const i = Math.min(Math.floor(Math.log(bytes) / Math.log(1024)), units.length - 1);
  return `${(bytes / 1024 ** i).toFixed(1)} ${units[i]}`;
}

